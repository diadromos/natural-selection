FINS=["M8 41 L14 42 M24 30 C28 36 28 45 24 51","M27 26 L29 15 L33 25 L36 13 L39 24 L42 14.5 L45 24.5 M48 25 C51 16 58 18 60 31",
      "M30 43 C34 47 38 47 41 44 M30 55 L27 63 L36 56 M47 54 C49 61 55 61 59 49"]
TAIL=[(64,38),(75,28),(71,40.5),(75,53),(64,43)]
def tail(a):
    c=(64,40.5);r=math.radians(a)
    pts=[(c[0]+(x-c[0])*math.cos(r)-(y-c[1])*math.sin(r),c[1]+(x-c[0])*math.sin(r)+(y-c[1])*math.cos(r)) if i not in(0,4) else (x,y) for i,(x,y) in enumerate(TAIL)]
    return 'M'+' L'.join('%.1f %.1f'%p for p in pts)
FISH={'left':-22,'center':0,'right':22}
fish={k:inner([FBODY,tail(a)]+FINS,[(17,36,2)]) for k,a in FISH.items()}
# ---- fit each kind into the viewBox with room for the 6.5px halo (no clipping); same transform for all frames of a kind
def fit(frames,margin=4.5):
    nums=[]
    for f in frames:
        for d in re.findall(r"d='([^']*)'",f):
            v=[float(x) for x in re.findall(r"-?\d+\.?\d*",d)]; nums+=list(zip(v[0::2],v[1::2]))
    xs=[a for a,b in nums]; ys=[b for a,b in nums]
    x0,x1,y0,y1=min(xs),max(xs),min(ys),max(ys)
    sc=min(1,(80-2*margin)/(x1-x0),(80-2*margin)/(y1-y0))
    tx=40-sc*(x0+x1)/2; ty=40-sc*(y0+y1)/2
    return sc,tx,ty
def wrap(body,t): return f"<g transform='translate({t[1]:.2f} {t[2]:.2f}) scale({t[0]:.3f})'>{body}</g>"
TB=fit(list(fly.values())+[PERCH]); TF=fit(list(fish.values()))
fly={k:wrap(v,TB) for k,v in fly.items()}; PERCH=wrap(PERCH,TB); fish={k:wrap(v,TF) for k,v in fish.items()}
ap=lambda p,t:[round(t[1]+t[0]*p[0],2),round(t[2]+t[0]*p[1],2)]
ANCH={'bird':ap((74,36.5),TB),'fish':ap((8,41),TF)}
