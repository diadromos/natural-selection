# perched (grab) = predator-bird.svg
PERCH=inner(["M62 22 C58 13 46 13 43 22 C38 30 29 36 21 45 L7 54 L13 57 L8 63 L24 56 C33 62 49 61 57 50 C61 44 63 39 63 35",
 "M62 22 L74 29 L63 35 M64 28.8 L71 29.2","M45 31 C37 34 29 42 25 51 C35 50 44 45 49 38","M38 60 L36 69 M46 58 L46 69 M28 70 L56 70"],[(53.5,25,2)])
