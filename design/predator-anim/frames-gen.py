import math,re
O='/workspace/natural-selection/design/predator-anim/'
def inner(paths,dots):
    d=' '.join(paths)
    halo=f"<g fill='none' stroke='#000' stroke-opacity='.55' stroke-width='6.5' stroke-linejoin='round' stroke-linecap='round'><path d='{d}'/>"+''.join(f"<circle cx='{x}' cy='{y}' r='{r+1.6}' fill='#000' fill-opacity='.55' stroke='none'/>" for x,y,r in dots)+"</g>"
    red=f"<g fill='none' stroke='#e00' stroke-width='3' stroke-linejoin='round' stroke-linecap='round'><path d='{d}'/>"+''.join(f"<circle cx='{x}' cy='{y}' r='{r}' fill='#e00' stroke='none'/>" for x,y,r in dots)+"</g>"
    return halo+red
svg=lambda body:f"<svg viewBox='0 0 80 80' width='80' height='80'>{body}</svg>"
# ---- bird in flight (faces right); beak tip at (74,37)
FB="M62 32 C58 24 47 24 44 31 C38 35 28 37 19 39 L6 34 L10 41 L6 48 L20 45 C30 50 46 50 56 45 C60 43 62.5 41 63 39"
BEAK="M62 32 L74 36.5 L63 39 M64 36 L71 36.5"
EYE=[(54,32.5,2)]
WINGS={'up':"M47 34 C45 22 41 11 34 3 L31 13 L24 13 L28 21 L21 24 L29 30 L33 37",
       'mid':"M47 35 C40 28 30 23 15 20 L21 26 L14 29 L24 32 L20 36 L33 39",
       'down':"M47 42 C45 54 42 65 36 75 L32 65 L25 65 L29 57 L22 54 L30 48 L33 43"}
